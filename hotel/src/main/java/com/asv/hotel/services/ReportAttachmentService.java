package com.asv.hotel.services;

import com.asv.hotel.dto.reportattachmendto.ReportAttachmentSimpleDTO;

/**
 * Сервисный интерфейс для работы с вложениями отчётов на уровне публичного API.
 * <p>
 * Предоставляет методы, предназначенные для использования в контроллерах и внешних слоях приложения.
 * Все операции учитывают права доступа текущего пользователя (через Spring Security).
 * <p>
 * Реализация гарантирует, что:
 * <ul>
 *   <li>Пользователь может получить только свои вложения или вложения, доступные по роли (ADMIN/MANAGER)</li>
 *   <li>Удаление разрешено только авторизованным пользователям с соответствующими правами</li>
 *   <li>ZIP-архивы формируются безопасно и содержат только разрешённые файлы</li>
 * </ul>
 */
public interface ReportAttachmentService {
    /**
     * Находит вложение по его идентификатору и возвращает DTO с бинарным содержимым.
     * <p>
     * Доступ разрешён, если:
     * <ul>
     *   <li>Текущий пользователь — владелец отчёта (staff), к которому привязано вложение, ИЛИ</li>
     *   <li>Текущий пользователь имеет роль ADMIN или MANAGER</li>
     * </ul>
     *
     * @param id идентификатор вложения
     * @return DTO с содержимым файла, или {@code null}, если доступ запрещён или вложение не найдено
     */
    ReportAttachmentSimpleDTO findReportAttachmentSimpleDTOByID(Long id);
    /**
     * Удаляет вложение по его идентификатору.
     * <p>
     * Доступ разрешён только пользователям с ролями ADMIN или MANAGER.
     *
     * @param id идентификатор удаляемого вложения
     * @throws com.asv.hotel.exceptions.HotelDataNotFoundException если вложение с указанным ID не существует
     */
    void deleteReportAttachmentById(Long id);
    /**
     * Формирует ZIP-архив со всеми вложениями отчёта с заданным ID и возвращает его как массив байтов.
     * <p>
     * Доступ разрешён, если:
     * <ul>
     *   <li>Текущий пользователь — владелец отчёта (staff), к которому привязаны вложения, ИЛИ</li>
     *   <li>Текущий пользователь имеет роль ADMIN или MANAGER</li>
     * </ul>
     * <p>
     * Если доступ запрещён или вложений нет, возвращается пустой массив {@code new byte[0]}.
     *
     * @param id идентификатор отчёта
     * @return байтовое представление ZIP-архива или пустой массив при отсутствии доступа/вложений
     */
    byte[] findByteArrayAttachmentsLikeZipByReportID(Long id);

}
