package com.asv.hotel.security.service;

import java.util.Set;

/**
 * Интерфейс сервиса для управления хранением и валидацией токенов.
 * Обеспечивает функции для добавления, проверки и удаления токенов аутентификации.
 *
 * <p>Данный сервис отвечает за:
 * <ul>
 *   <li>Хранение активных пользователей</li>
 *   <li>Проверку валидности и срока действия токенов</li>
 *   <li>Управление жизненным циклом токенов</li>
 *   <li>Удаление токенов</li>
 * </ul>
 */
public interface TokenStorageService {
    /**
     * Добавляет токен для указанного пользователя в хранилище.
     *
     * <p>Токен связывается с идентификатором пользователя и считается активным
     * до момента его явного удаления или истечения срока действия.
     *
     * @param userId уникальный идентификатор пользователя
     * @param token  токен аутентификации для добавления
     */
    void addTokens(Long userId, String token);

    /**
     * Проверяет, является ли токен истекшим.
     *
     * @param token токен для проверки
     * @return false если токен истек или недействителен, true если токен активен
     */
    boolean isTokenExpired(String token);

    /**
     * Проверяет, активен ли указанный токен для конкретного пользователя.
     *
     * @param userId уникальный идентификатор пользователя
     * @param token  токен для проверки
     * @return true если токен активен и принадлежит пользователю, false в противном случае
     */
    boolean isTokenActiveForUser(Long userId, String token);

    /**
     * Удаляет конкретный токен из хранилища.
     *
     * @param token токен для удаления
     */
    void removeToken(String token);

    /**
     * Удаляет конкретный токен для указанного пользователя.
     *
     * @param userId уникальный идентификатор пользователя
     * @param token  конкретный токен для удаления
     */
    void removeTokenForUser(Long userId, String token);

    /**
     * Удаляет все активные токены указанного пользователя.
     *
     * @param userId уникальный идентификатор пользователя
     */
    void removeAllUserTokens(Long userId);

    /**
     * Полностью очищает хранилище токенов.
     */
    void clearAllTokens();

    /**
     * Возвращает множество активных токенов для указанного пользователя.
     *
     * @param userId уникальный идентификатор пользователя
     * @return множество активных токенов пользователя или пустое множество если токенов нет
     */
    Set<String> getUserActiveTokens(Long userId);
}
